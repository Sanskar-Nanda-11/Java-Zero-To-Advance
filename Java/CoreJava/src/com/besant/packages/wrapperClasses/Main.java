package com.besant.packages.wrapperClasses;

public class Main {

	public static void main(String[] args) {
			String s = "abc";
			
			int i = 20;
			
			//Integer is a wrapper class for primitive datatype int
			Integer j = 20;
			//wrapper classes for other datatypes
			Byte b;
			Short sh;
			Long l;
			Double d;
			Float f;
			Boolean bool;
			Character c;
			
			System.out.println(i+j);
	}
	
}
